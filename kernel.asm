[BITS 32]

section .text
KERNEL_BASE equ 0x9000
global start_stage2
start_stage2:
    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax
    mov ss, ax
    mov esp, 0x90000

    extern kmain
    call kmain
    jmp $
%if 0
    call clear_screen

    mov esi, msg_booting
    mov edi, 0xB8000
    call print_string

    mov esi, msg_step1
    mov edi, 0xB8000 + 160
    call print_string

    mov esi, msg_step2
    mov edi, 0xB8000 + 320
    call print_string

    call init_pic
    lidt [idt_descriptor]

    mov esi, msg_step3
    mov edi, 0xB8000 + 480
    call print_string

    call init_idt

    mov esi, msg_step4
    mov edi, 0xB8000 + 640
    call print_string

    mov esi, msg_prompt
    mov edi, 0xB8000 + 800
    call print_string

    mov word [cursor_x], 10
    mov word [cursor_y], 5
    mov byte [last_scancode], 0
    mov byte [feedback_eoi], ' '

    ; 键盘缓冲区
    mov word [buf_head], 0
    mov word [buf_tail], 0
    mov word [buf_len], 0
    mov word [shift_state], 0

    call update_hardware_cursor
    
    

    sti

.hang:
    hlt
    jmp .hang
%endif
; ===== 异常处理 =====
double_fault_handler:
    cli
    mov edi, 0xB8000
    mov word [edi], 0x4F00 | 'D'
    mov word [edi+2], 0x4F00 | 'F'
    mov al, 0x20
    out 0x20, al
    hlt
    jmp $
exception_handler:
    pushad
    mov edi, 0xB8000
    mov esi, msg_exc
    call print_string
    mov al, 0x20
    out 0x20, al
    popad
    iret

; ===== 键盘中断 =====
isr_keyboard:
    cld
    pusha
    in al, 0x60
    mov [last_scancode], al

    cmp al, 0x01
    jne .check_shift
    cmp byte [display_mode], 1
    jne .check_shift
    mov byte [display_mode], 0
    jmp start_stage2
.check_shift:
    ; Shift 处理
    cmp al, 0x2A
    je .set_shift
    cmp al, 0xAA
    je .clear_shift
    cmp al, 0x36
    je .set_shift
    cmp al, 0xB6
    je .clear_shift
    jmp .not_shift
.set_shift:
    mov word [shift_state], 1
    jmp .end
.clear_shift:
    mov word [shift_state], 0
    jmp .end

.not_shift:
    ; 忽略 E0/E1/F0 和释放码
    cmp al, 0xE0
    je .end
    cmp al, 0xE1
    je .end
    cmp al, 0xF0
    je .end
    test al, 0x80
    jnz .end

    cmp al, 0x0E
    je .backspace
    cmp al, 0x1C
    je .enter

    cmp al, key_map_size
    jae .end
    xor ebx, ebx
    mov bl, al
    cmp bl, 0
    je .end

    mov ax, [buf_len]
    cmp ax, BUF_SIZE
    jae .end

    mov al, [key_map + ebx]
    cmp word [shift_state], 1
    jne .no_shift
    cmp al, 'a'
    jb .no_shift
    cmp al, 'z'
    ja .no_shift
    sub al, 32
.no_shift:
    mov bx, [buf_head]
    mov [key_buffer + ebx], al
    inc bx
    and bx, (BUF_SIZE-1)
    mov [buf_head], bx
    inc word [buf_len]

    mov [temp_char], al
    je .get_cursor_pos
    call get_cursor_pos
    mov al, [temp_char]
    mov byte [edi], al
    mov byte [edi+1], 0x0F
    call inc_cursor
    call update_hardware_cursor
    jmp .end
.get_cursor_pos:
    mov bx, 100
    mov cx, 100
    mov al, 0x0F
    call draw_pixel
    jmp .end

.backspace:
    cmp byte [display_mode], 1
    je .end

    cmp word [buf_len], 0
    je .end
    dec word [buf_len]
    mov bx, [buf_head]
    dec bx
    and bx, (BUF_SIZE-1)
    mov [buf_head], bx

    call dec_cursor
    call get_cursor_pos
    mov byte [edi], 0x20
    mov byte [edi+1], 0x07
    call update_hardware_cursor
    jmp .end

.enter:
    ; cmp byte [display_mode], 0
    ; je .end
    ; 换行
    mov word [cursor_x], 0
    inc word [cursor_y]
    cmp word [cursor_y], 25
    jb .enter_no_scroll
    dec word [cursor_y]
    call scroll_screen
.enter_no_scroll:
    call update_hardware_cursor

    ; 执行命令
    movzx ebx, word [buf_head]
    movzx ecx, word [buf_len]
    sub ebx, ecx
    and ebx, (BUF_SIZE-1)
    mov esi, key_buffer
    add esi, ebx
    mov cx, [buf_len]
    cmp cx, 0
    je .cmd_done

    ; 临时在末尾加 0
    mov bx, [buf_head]
    ; dec bx
    and bx, (BUF_SIZE-1)
    mov byte [key_buffer + ebx], 0

    cmp word [buf_len], 5
    jne .check_gfx
    mov esi, key_buffer
    mov edi, cmd_clear
    mov cx, 5
    repe cmpsb
    je .cmd_clear
    jmp .unknown_cmd
.check_gfx:
    cmp word [buf_len], 3
    jne .check_text
    mov esi, key_buffer
    mov edi, cmd_gfx
    mov cx, 3
    repe cmpsb
    je .cmd_gfx
    jmp .unknown_cmd
.check_text:
    cmp word [buf_len], 4
    jne .unknown_cmd
    movzx ebx, word [buf_head]
    movzx ecx, word [buf_len]
    sub ebx, ecx
    and ebx, (BUF_SIZE-1)
    mov esi, key_buffer
    add esi, ebx
    mov edi, cmd_text
    mov cx, 4
    repe cmpsb
    je .cmd_text
    movzx ebx, word [buf_head]
    movzx ecx, word [buf_len]
    sub ebx, ecx
    and ebx, (BUF_SIZE-1)
    mov esi, key_buffer
    add esi, ebx
    mov edi, cmd_help
    mov cx, 4
    repe cmpsb
    je .cmd_help
    jmp .unknown_cmd
.cmd_help:
    call get_cursor_pos
    mov esi, msg_help
    call print_line
    jmp .cmd_done
.unknown_cmd:
    call get_cursor_pos
    mov esi, msg_unknown
    call print_line
    jmp .cmd_done
.cmd_done:
    mov word [buf_head], 0
    mov word [buf_tail], 0
    mov word [buf_len], 0
    call get_cursor_pos
    mov esi, msg_prompt
    call print_string
    add word [cursor_x], 10
    call update_hardware_cursor
    jmp .end
.cmd_clear:
    call clear_screen
    jmp .cmd_done
.cmd_gfx:
    cli
    xor ecx, ecx
    call set_vga_gfx
    mov byte [display_mode], 1
    push ax
    mov ax, 0x10
    mov es, ax
    pop ax
    mov edi, 0xA0000
    mov ecx, 320*200
    mov al, 1
    rep stosb
    mov esi, img_raw
    mov edi, 0xA0000 + (320 * 84) + 144
    mov ebx, 48
.logo_row:
    mov ecx, 48
.logo_col:
    mov al, [esi]
    cmp al, 0x00
    je .skip_pixel
    mov [edi], al
.skip_pixel:
    inc esi
    inc edi
    loop .logo_col
    add edi, 320 - 48
    dec ebx
    jnz .logo_row
    sti
    jmp .cmd_done
.cmd_text:
    mov byte [display_mode], 0
    jmp start_stage2
.end:
    call update_feedback
    mov al, 0x20
    out 0x20, al
    popa
    iret

; ===== 辅助函数 =====
clear_screen:
    mov edi, 0xB8000
    mov ecx, 2000
    mov ax, 0x0720
    rep stosw
    mov word [cursor_x], 0
    mov word [cursor_y], 0
    call update_hardware_cursor
    ret

print_string:
    pushad
    mov ah, 0x0F
.loop:
    lodsb
    cmp al, 0
    je .done
    mov byte [edi], al
    mov byte [edi+1], ah
    add edi, 2
    jmp .loop
.done:
    popad
    ret

print_line:
    call print_string
    mov word [cursor_x], 0
    inc word [cursor_y]
    cmp word [cursor_y], 25
    jb .done
    dec word [cursor_y]
    call scroll_screen
.done:
    call update_hardware_cursor
    ret

set_vga_text:
    pushad
    mov si, set_vga_text
    mov dx, 0x3C2
    lodsb
    out dx, al
    mov dx, 0x3C4
    mov cx, 5
.seq:
    mov al, 5 
    sub al, cl
    out dx, al
    inc dx
    lodsb
    out dx, al
    dec dx
    loop .seq
    mov dx, 0x3D4
    mov al, 0x11
    out dx, al
    inc dx
    in al, dx
    and al, 0x7F
    out dx, al
    dec dx
    mov cx, 25
.crtc:
    mov al, 25
    sub al, cl
    out dx, al
    inc dx
    lodsb
    out dx, al
    dec dx
    loop .crtc
    mov dx, 0x3CE
    mov cx, 9
    mov si, set_vga_gfx
.gfx:
    mov al, 9
    sub al, cl
    out dx, al
    inc dx
    lodsb
    out dx, al
    dec dx
    loop .gfx
    mov dx, 0x3DA
    in al, dx
    mov dx, 0x3C0
    mov cx, 21
.attr:
    mov al, 21 
    sub al, cl
    out dx, al
    lodsb
    out dx, al
    loop .attr
    mov al, 0x20
    out dx, al
    popad
    ret 

scroll_screen:
    pushad
    mov edi, 0xB8000
    mov esi, 0xB8000 + 160
    mov ecx, 24 * 80
    rep movsw
    mov ecx, 80
    mov ax, 0x0720
    rep stosw
    popad
    ret

init_pic:
    mov al, 0x11
    out 0x20, al
    out 0xA0, al
    mov al, 0x20
    out 0x21, al
    mov al, 0x28
    out 0xA1, al
    mov al, 0x04
    out 0x21, al
    mov al, 0x02
    out 0xA1, al
    mov al, 0x01
    out 0x21, al
    mov al, 0xFD
    out 0x21, al
    mov al, 0xFF
    out 0xA1, al
    ret

init_idt:
    mov edi, idt_start
    mov ecx, 32
    mov ebx, exception_handler_linear
.set_exc:
    mov word [edi], bx
    mov word [edi+2], 0x08
    mov byte [edi+4], 0x00
    mov byte [edi+5], 0x8E
    mov eax, ebx
    shr eax, 16
    mov word [edi+6], ax
    add edi, 8
    loop .set_exc

    mov eax, isr_timer_linear
    mov word [idt_start + 32*8], ax
    mov word [idt_start + 32*8+2], 0x08
    mov byte [idt_start + 32*8+4], 0x00
    mov byte [idt_start + 32*8+5], 0x8E
    shr eax, 16
    mov word [idt_start + 32*8+6], ax

    mov eax, double_fault_handler_linear
    mov word [idt_start + 8*8], ax
    mov word [idt_start + 8*8+2], 0x08
    mov byte [idt_start + 8*8+4], 0x00
    mov byte [idt_start + 8*8+5], 0x8E
    shr eax, 16
    mov word [idt_start + 8*8+6], ax

    mov eax, isr_keyboard_linear
    mov word [idt_start + 33*8], ax
    mov word [idt_start + 33*8+2], 0x08
    mov byte [idt_start + 33*8+4], 0x00
    mov byte [idt_start + 33*8+5], 0x8E
    shr eax, 16
    mov word [idt_start + 33*8+6], ax

    lidt [idt_descriptor]
    ret

update_feedback:
    pushad
    mov edi, 0xB8000 + (80*25 - 2)*2
    movzx eax, byte [last_scancode]
    call print_hex_byte_at
    mov al, [feedback_eoi]
    mov byte [edi+4], al
    mov byte [edi+5], 0x0A
    popad
    ret

print_hex_byte_at:
    push eax
    shr al, 4
    call .nibble
    pop eax
    call .nibble
    ret
.nibble:
    and al, 0x0F
    cmp al, 10
    jb .digit
    add al, 'A'-10
    jmp .show
.digit:
    add al, '0'
.show:
    mov byte [edi], al
    mov byte [edi+1], 0x0A
    add edi, 2
    ret

get_cursor_pos:
    movzx eax, word [cursor_y]
    cmp eax, 24
    jbe .y_ok
    mov eax, 24
.y_ok:
    imul eax, 80
    movzx ebx, word [cursor_x]
    cmp ebx, 79
    jbe .x_ok
    mov ebx, 79
.x_ok:
    add eax, ebx
    shl eax, 1
    add eax, 0xB8000
    mov edi, eax
    ret

inc_cursor:
    inc word [cursor_x]
    cmp word [cursor_x], 80
    jb .check_y
    mov word [cursor_x], 0
    inc word [cursor_y]
.check_y:
    cmp word [cursor_y], 25
    jb .done
    pushad
    call scroll_screen
    popad
    mov word [cursor_y], 24
.done:
    ret

dec_cursor:
    cmp word [cursor_x], 0
    jne .ok
    cmp word [cursor_y], 0
    je .done
    mov word [cursor_x], 79
    dec word [cursor_y]
    jmp .done
.ok:
    dec word [cursor_x]
.done:
    ret

update_hardware_cursor:
    pushad
    cmp byte [display_mode], 1
    je .skip
    movzx ax, [cursor_y]
    imul ax, 80
    add ax, [cursor_x]
    mov bx, ax
    mov dx, 0x3D4
    mov al, 0x0E
    out dx, al
    inc dx
    mov al, bh
    out dx, al
    dec dx
    mov al, 0x0F
    out dx, al
    inc dx
    mov al, bl
    out dx, al
    popad
    ret
.skip:
    popad
    ret
set_vga_gfx:
    pushad
    mov esi, vga_gfx_regs

    mov dx, 0x3C2
    lodsb
    out dx, al

    mov dx, 0x3C4
    mov cx, 5
.seq_loop:
    mov al, 5
    sub al, cl
    out dx, al
    inc dx
    lodsb
    out dx, al
    dec dx
    loop .seq_loop

    mov dx, 0x3D4
    mov al, 0x03
    out dx, al
    inc dx
    in al, dx
    or al, 0x80
    out dx, al
    dec dx
    mov cx, 25
.crtc_loop:
    mov al, 25
    sub al, cl
    out dx, al
    inc dx
    lodsb
    out dx, al
    dec dx
    loop .crtc_loop

    mov dx, 0x3CE
    mov cx, 9
.gfx_loop:
    mov al, 9
    sub al, cl
    out dx, al
    inc dx
    lodsb
    out dx, al
    dec dx
    loop .gfx_loop

    mov dx, 0x3DA
    in al, dx
    mov dx, 0x3C0
    mov cx, 21
.attr_loop:
    mov al, 21
    sub al, cl
    out dx, al
    lodsb
    out dx, al
    loop .attr_loop
    mov al, 0x20
    out dx, al

    popad
    ret
draw_pixel:
    pushad
    mov edi, 0xA0000
    mov eax, ecx
    imul eax, 320
    add eax, ebx
    add edi, eax
    mov [edi], al
    popad
    ret

global system_ticks
system_ticks: dd 0
isr_timer:
    pusha
    inc dword [system_ticks]  ; 注意：这个变量要在 C 语言里定义，或者在这里定义
    mov al, 0x20
    out 0x20, al
    popa
    iret
